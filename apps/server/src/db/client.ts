import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { drizzle as drizzlePg } from 'drizzle-orm/node-postgres';
import { migrate as migratePg } from 'drizzle-orm/node-postgres/migrator';
import { drizzle as drizzlePglite } from 'drizzle-orm/pglite';
import { migrate as migratePglite } from 'drizzle-orm/pglite/migrator';
import type { SQL } from 'drizzle-orm';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import pg from 'pg';
import * as schema from './schema';

export type Schema = typeof schema;

/** Either driver's database. Repositories take this, so they also accept a transaction. */
export type Db = PgDatabase<PgQueryResultHKT, Schema>;

/** Generated by drizzle-kit (see drizzle.config.ts) and checked in. */
export const MIGRATIONS_DIR = fileURLToPath(new URL('../../drizzle', import.meta.url));

/** Any fixed number works; it only has to match across server processes. */
const MIGRATION_LOCK_KEY = 4_727_301;

export interface CreateDbOptions {
  /** Postgres connection string. Defaults to DATABASE_URL; with neither, PGlite is used. */
  url?: string;
  /** PGlite data directory. Defaults to PGLITE_DIR; with neither, PGlite runs in memory. */
  pgliteDir?: string;
  /** Skip DATABASE_URL and PGLITE_DIR, so tests never touch a real database. */
  ignoreEnv?: boolean;
  /** PGlite only: how often to vacuum. Tests shorten it. */
  vacuumEveryMs?: number;
}

/**
 * PGlite runs no autovacuum, and a table's snapshot is rewritten on every
 * change, so each save would leave its old copy on disk for good (about
 * 1.5 MB a hand). Vacuuming this often lets new saves reuse that space, and
 * the checkpoint after it lets the write-ahead log reuse its files.
 */
const VACUUM_EVERY_MS = 5 * 60_000;

const closers = new WeakMap<object, () => Promise<void>>();

/**
 * Opens the database and applies pending migrations before returning, so
 * callers can query right away. Postgres when a URL is configured, otherwise
 * PGlite (in memory, or on disk with PGLITE_DIR for local development).
 */
export async function createDb(opts: CreateDbOptions = {}): Promise<Db> {
  const url = opts.url || (opts.ignoreEnv ? undefined : process.env.DATABASE_URL) || undefined;
  if (url) return openPostgres(url);
  const dataDir = opts.pgliteDir || (opts.ignoreEnv ? undefined : process.env.PGLITE_DIR) || undefined;
  return openPglite(dataDir, opts.vacuumEveryMs ?? VACUUM_EVERY_MS);
}

/**
 * Rows of a raw SQL query. `db.execute` is typed per driver; both drivers
 * return `{ rows }`, so this gives raw queries one shape on the shared Db type.
 */
export async function queryRows<T extends Record<string, unknown>>(db: Db, query: SQL): Promise<T[]> {
  const res = (await db.execute(query)) as { rows: T[] };
  return res.rows;
}

/** Closes the pool or the PGlite instance behind a database from createDb. */
export async function closeDb(db: Db): Promise<void> {
  const close = closers.get(db);
  closers.delete(db);
  await close?.();
}

async function openPostgres(url: string): Promise<Db> {
  const pool = new pg.Pool({ connectionString: url });
  // An idle connection dropped by the server (maintenance, failover, a paused database) is
  // replaced on the next query; without a listener it would be an uncaught exception.
  pool.on('error', (e) => console.error('postgres connection lost', e.message));
  try {
    // Several server processes may boot at once; the advisory lock lets one migrate at a time.
    const client = await pool.connect();
    try {
      await client.query('select pg_advisory_lock($1)', [MIGRATION_LOCK_KEY]);
      try {
        await migratePg(drizzlePg(client), { migrationsFolder: MIGRATIONS_DIR });
      } finally {
        await client.query('select pg_advisory_unlock($1)', [MIGRATION_LOCK_KEY]);
      }
    } finally {
      client.release();
    }
  } catch (err) {
    await pool.end();
    throw err;
  }
  const db = drizzlePg(pool, { schema });
  closers.set(db, () => pool.end());
  return db;
}

async function openPglite(dataDir: string | undefined, vacuumEveryMs: number): Promise<Db> {
  // PGlite creates only the last folder of the path.
  if (dataDir) mkdirSync(path.dirname(path.resolve(dataDir)), { recursive: true });
  const client = new PGlite(dataDir);
  const db = drizzlePglite(client, { schema });
  try {
    await migratePglite(db, { migrationsFolder: MIGRATIONS_DIR });
  } catch (err) {
    await client.close();
    throw err;
  }
  // Give back what runs without vacuuming left behind. Only the latest snapshot of each table is live, so this is
  // quick, but it needs room for them: on a nearly full disk it fails, and the server still starts.
  await client.exec('VACUUM FULL table_snapshots').catch(async (err: Error) => {
    console.error('vacuum full failed', err.message);
    await client.exec('VACUUM').catch(() => {});
  });
  // PGlite also never checkpoints on its own (only when it closes), so its write-ahead log would grow just as fast.
  // exec, query and transactions share one lock, so neither lands inside someone's transaction.
  const vacuum = setInterval(() => {
    client
      .exec('VACUUM')
      .then(() => client.exec('CHECKPOINT'))
      .catch((err: Error) => console.error('vacuum failed', err.message));
  }, vacuumEveryMs);
  vacuum.unref();
  closers.set(db, async () => {
    clearInterval(vacuum);
    await client.close();
  });
  return db;
}
